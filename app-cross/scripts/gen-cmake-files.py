#!/usr/bin/env python3
"""Generate target source lists from folder ownership and platform filenames."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE_FOLDERS = {"business", "context", "observables"}
# Composition needs UI adapters; the native issue handoff itself has no wx dependency.
TARGET_OVERRIDES = {
    "app/observables/AppContext.cc": "APP_SOURCES",
    "app/ui/platform/WindowsIssueHandoff.cc": "CORE_SOURCES",
}
PLATFORMS = {"Windows": "WIN32", "POSIX": "NOT WIN32"}


def classify(path):
    if path.parts[0] == "models":
        return "MODEL_SOURCES", None
    target = TARGET_OVERRIDES.get(path.as_posix())
    if target is None:
        target = "CORE_SOURCES" if path.parts[1] in CORE_FOLDERS else "APP_SOURCES"
    condition = None
    if path.parent.name == "platform":
        condition = next((value for prefix, value in PLATFORMS.items()
                          if path.name.startswith(prefix)), None)
    return target, condition


def render_sources(target, paths, condition=None):
    indent = "    " if condition else ""
    command = f"list(APPEND {target}" if condition else f"set({target}"
    lines = [f"if({condition})"] if condition else []
    lines.append(indent + command)
    for path in paths:
        value = path.as_posix()
        if target != "APP_SOURCES":
            value = f'"${{CMAKE_CURRENT_LIST_DIR}}/{value}"'
        lines.append(indent + "    " + value)
    lines.append(indent + ")")
    if condition:
        lines.append("endif()")
    return "\n".join(lines) + "\n"


def main():
    groups = {}
    paths = sorted((ROOT / "app").rglob("*.cc")) + sorted((ROOT / "models").glob("*.cc"))
    for absolute in paths:
        path = absolute.relative_to(ROOT)
        groups.setdefault(classify(path), []).append(path)
    output = "# Generated by scripts/gen-cmake-files.py.\n"
    for target in ("APP_SOURCES", "CORE_SOURCES", "MODEL_SOURCES"):
        output += render_sources(target, groups.get((target, None), []))
        for condition in PLATFORMS.values():
            paths = groups.get((target, condition), [])
            if paths:
                output += render_sources(target, paths, condition)
    (ROOT / "files.cmake").write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
