#!/usr/bin/env python3
# Keep frontend, core, and model sources separate; platform sources stay conditional.
import os
from pathlib import Path

os.chdir(Path(__file__).resolve().parent.parent)

sources = sorted(p.as_posix() for p in Path("app").rglob("*.cc")
                 if not any(part in ("business", "observables", "context", "platform") for part in p.parts))
sources += sorted(p.as_posix() for p in Path("app/ui/platform").glob("*.cc")
                  if not p.name.startswith(("Windows", "POSIX")))
# Composition uses native adapters; context helpers stay in the portable core.
sources.append("app/observables/AppContext.cc")
sources.sort()
windows = sorted(p.as_posix() for directory in ("app/ui/platform", "app/business/platform")
                 for p in Path(directory).glob("Windows*.cc"))
posix = sorted(p.as_posix() for directory in ("app/ui/platform", "app/business/platform")
               for p in Path(directory).glob("POSIX*.cc"))
core = sorted(p.as_posix() for directory in ("app/business", "app/observables", "app/context")
              for p in Path(directory).rglob("*.cc") if p.as_posix() not in windows + posix and p.name != "AppContext.cc")
models = sorted(p.as_posix() for p in Path("models").glob("*.cc"))
Path("files.cmake").write_text(
    "# Generated by scripts/gen-cmake-files.py.\n" +
    "set(APP_SOURCES\n" +
    "".join("    " + p + "\n" for p in sources) + ")\n" +
    "if(WIN32)\n    list(APPEND APP_SOURCES\n" +
    "".join("        " + p + "\n" for p in windows) + "    )\nelse()\n    list(APPEND APP_SOURCES\n" +
    "".join("        " + p + "\n" for p in posix) + "    )\nendif()\n" +
    "".join("set(" + name + "\n" +
            "".join('    "${CMAKE_CURRENT_LIST_DIR}/' + p + '"\n' for p in paths) +
            ")\n" for name, paths in (("CORE_SOURCES", core), ("MODEL_SOURCES", models))),
    encoding="utf-8", newline="\n")
