"""Generate the cross-platform C++ catalogs from Apple's .strings files."""

import argparse
import json
from pathlib import Path
import re


NOTICE = '// Generated by scripts/import-apple-strings.py. Do not edit.'
LICENSE = ['// SPDX-FileCopyrightText: 2026 Davide De Rosa', '//', '// SPDX-License-Identifier: GPL-3.0']
IGNORED = re.compile(r'(?:\s+|//[^\r\n]*|/\*(?s:.*?)\*/)*')
ENTRY = re.compile(r'"((?:\\.|[^"\\])*)"\s*=\s*"((?:\\.|[^"\\])*)"\s*;')


def unescape(value):
    def replace(match):
        escape = match[1]
        if escape in ('U', 'u'):
            raise ValueError(f'Invalid Apple escape: {escape}')
        if len(escape) == 5:
            return chr(int(escape[1:], 16))
        return {'n': '\n', 'r': '\r', 't': '\t'}.get(escape, escape)

    value = re.sub(r'\\([Uu][0-9a-fA-F]{4}|.)', replace, value)
    # Apple Unicode escapes can encode supplementary characters as UTF-16 pairs.
    return value.encode('utf-16-le', errors='surrogatepass').decode('utf-16-le')


def read_strings(path):
    text = path.read_text(encoding='utf-8-sig')
    entries = {}
    position = 0
    while position < len(text):
        position = IGNORED.match(text, position).end()
        if position == len(text):
            break
        match = ENTRY.match(text, position)
        if not match:
            raise ValueError(f'{path}: invalid .strings entry at offset {position}')
        key = unescape(match[1])
        if key in entries:
            raise ValueError(f'{path}: duplicate key {key}')
        entries[key] = unescape(match[2])
        position = match.end()
    return entries


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def generate(source, output_path, keys_path):
    base = read_strings(source / 'en.lproj' / 'Localizable.strings')
    catalogs = {}
    for directory in sorted(source.glob('*.lproj')):
        if not directory.is_dir():
            continue
        locale = directory.stem.replace('-', '_')
        if locale in catalogs:
            raise ValueError(f'Duplicate locale: {locale}')
        entries = read_strings(directory / 'Localizable.strings')
        for key in base:
            if key not in entries and not key.startswith('android.'):
                raise ValueError(f'{locale}: missing key {key}')
        for key in entries:
            if key not in base:
                raise ValueError(f'{locale}: unknown key {key}')
        catalogs[locale] = entries

    identifiers = {}
    for key in base:
        identifier = ''.join(part[:1].upper() + part[1:] for part in re.split(r'[^a-zA-Z0-9]+', key))
        if not re.fullmatch(r'[A-Z][a-zA-Z0-9]*', identifier) or identifier in identifiers:
            raise ValueError(f'Invalid or colliding C++ identifier for key: {key}')
        identifiers[identifier] = key

    keys = LICENSE + [NOTICE, '#pragma once', 'namespace Passepartout {', 'enum class StringKey {']
    keys.extend(f'    {identifier},' for identifier in identifiers)
    keys.extend(['};', 'constexpr const char *StringKeyName(StringKey key) {', '    switch (key) {'])
    keys.extend(f'        case StringKey::{identifier}: return {literal(key)};'
                for identifier, key in identifiers.items())
    keys.extend(['    }', '    return "";', '}', '}'])
    # Individual literals stay below MSVC's string literal size limit.
    output = LICENSE + ['', NOTICE]
    output.extend(f'    {{{literal(locale)}, {literal(key)}, {literal(entries[key])}}},'
                  for locale, entries in catalogs.items() for key in base if key in entries)
    for path, lines in ((output_path, output), (keys_path, keys)):
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('w', encoding='utf-8', newline='\n') as stream:
            stream.write('\n'.join(lines) + '\n')
    print(f'Imported {len(catalogs)} Apple catalogs into {output_path}')


def main():
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-directory', type=Path,
                        default=root.parent / 'app-apple/Sources/AppStrings/Resources')
    parser.add_argument('--output-path', type=Path, default=root / 'app/strings/strings.inc')
    parser.add_argument('--keys-path', type=Path)
    args = parser.parse_args()
    generate(args.source_directory, args.output_path,
             args.keys_path or args.output_path.with_name('strings_keys.h'))


if __name__ == '__main__':
    main()
