#!/bin/bash
set -e
export LC_ALL=C
script_dir="$(cd "$(dirname "$0")" && pwd)"
cd "$script_dir/.."
# Keep frontend, core, and model sources separate; platform sources stay conditional.
python3 - <<'PYTHON'
from pathlib import Path
sources = sorted(p.as_posix() for p in Path("app").rglob("*.cc")
                 if not any(part in ("business", "observables", "platform") for part in p.parts))
windows = sorted(p.as_posix() for p in Path("app/platform").glob("windows_*.cc"))
core = sorted(p.as_posix() for directory in ("app/business", "app/observables")
              for p in Path(directory).rglob("*.cc"))
models = sorted(p.as_posix() for p in Path("models").glob("*.cpp"))
Path("files.cmake").write_text(
    "# Generated by scripts/gen-cmake-files.sh.\n" +
    "set(APP_SOURCES\n" +
    "".join("    " + p + "\n" for p in sources) + ")\n" +
    "if(WIN32)\n    list(APPEND APP_SOURCES\n" +
    "".join("        " + p + "\n" for p in windows) + "    )\nendif()\n" +
    "".join("set(" + name + "\n" +
            "".join('    "${CMAKE_CURRENT_LIST_DIR}/' + p + '"\n' for p in paths) +
            ")\n" for name, paths in (("CORE_SOURCES", core), ("MODEL_SOURCES", models))))
PYTHON
