[CmdletBinding()]
param(
    [string]$SourceDirectory = "$PSScriptRoot/../../app-apple/Sources/AppStrings/Resources",
    [string]$OutputPath = "$PSScriptRoot/../app/strings/strings.inc",
    [string]$KeysPath = ""
)
# Constants
$fallbackLocale = 'en'
$catalogSuffix = '.lproj'
$catalogName = 'Localizable.strings'
$optionalKeyPrefix = 'android.'
$keysFileName = 'strings_keys.h'
$generatedNotice = '// Generated by scripts/import-apple-strings.ps1. Do not edit.'

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function ConvertFrom-AppleEscape([string]$Value) {
    [regex]::Replace($Value, '\\(U[0-9a-fA-F]{4}|u[0-9a-fA-F]{4}|.)', {
        param($Match)
        $escape = $Match.Groups[1].Value
        switch -CaseSensitive ($escape) {
            'n' { "`n" }
            'r' { "`r" }
            't' { "`t" }
            default {
                if ($escape -cmatch '^[Uu][0-9a-fA-F]{4}$') {
                    [string][char][Convert]::ToInt32($escape.Substring(1), 16)
                } elseif ($escape.Length -eq 1 -and $escape -cnotmatch '^[Uu]$') {
                    $escape
                } else {
                    throw "Invalid Apple escape: $escape"
                }
            }
        }
    })
}

function Read-AppleStrings([string]$Path) {
    $text = [IO.File]::ReadAllText($Path)
    $entries = [ordered]@{}
    $position = 0
    $ignored = [regex]'\G(?:\s+|//[^\r\n]*|/\*(?s:.*?)\*/)*'
    $entry = [regex]'\G"((?:\\.|[^"\\])*)"\s*=\s*"((?:\\.|[^"\\])*)"\s*;'
    while ($position -lt $text.Length) {
        $position += $ignored.Match($text, $position).Length
        if ($position -eq $text.Length) { break }
        $match = $entry.Match($text, $position)
        if (!$match.Success) { throw "${Path}: invalid .strings entry at offset $position" }
        $key = ConvertFrom-AppleEscape $match.Groups[1].Value
        if ($entries.Contains($key)) { throw "${Path}: duplicate key $key" }
        $entries[$key] = ConvertFrom-AppleEscape $match.Groups[2].Value
        $position += $match.Length
    }
    return $entries
}

# Emit individual UTF-8 literals to stay below MSVC's string literal size limit.
$catalogs = [ordered]@{}
$base = Read-AppleStrings (Join-Path $SourceDirectory "$fallbackLocale$catalogSuffix/$catalogName")
foreach ($directory in Get-ChildItem -LiteralPath $SourceDirectory -Directory -Filter "*$catalogSuffix" | Sort-Object Name) {
    $locale = $directory.Name.Substring(0, $directory.Name.Length - $catalogSuffix.Length).Replace('-', '_')
    $entries = Read-AppleStrings (Join-Path $directory.FullName $catalogName)
    foreach ($key in $base.Keys) {
        if (!$entries.Contains($key) -and !$key.StartsWith($optionalKeyPrefix)) {
            throw "${locale}: missing key $key"
        }
    }
    foreach ($key in $entries.Keys) {
        if (!$base.Contains($key)) { throw "${locale}: unknown key $key" }
    }
    $catalogs[$locale] = $entries
}
if (!$catalogs.Contains($fallbackLocale)) { throw 'English fallback catalog is required' }
if (!$KeysPath) { $KeysPath = Join-Path (Split-Path -Parent $OutputPath) $keysFileName }
$keys = [Text.StringBuilder]::new()
[void]$keys.AppendLine($generatedNotice)
[void]$keys.AppendLine('#pragma once')
[void]$keys.AppendLine('namespace Passepartout {')
[void]$keys.AppendLine('enum class StringKey {')
$identifiers = [ordered]@{}
foreach ($key in $base.Keys) {
    $identifier = (($key -split '[^a-zA-Z0-9]+') | ForEach-Object {
        $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1)
    }) -join ''
    if ($identifier -cnotmatch '^[A-Z][a-zA-Z0-9]*$' -or $identifiers.Contains($identifier)) {
        throw "Invalid or colliding C++ identifier for key: $key"
    }
    $identifiers[$identifier] = $key
    [void]$keys.AppendLine("    $identifier,")
}
[void]$keys.AppendLine('};')
[void]$keys.AppendLine('constexpr const char *StringKeyName(StringKey key) {')
[void]$keys.AppendLine('    switch (key) {')
foreach ($identifier in $identifiers.Keys) {
    $literal = ConvertTo-Json -InputObject ([string]$identifiers[$identifier]) -Compress
    [void]$keys.AppendLine("        case StringKey::${identifier}: return $literal;")
}
[void]$keys.AppendLine('    }')
[void]$keys.AppendLine('    return "";')
[void]$keys.AppendLine('}')
[void]$keys.AppendLine('}')
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine($generatedNotice)
foreach ($locale in $catalogs.Keys) {
    foreach ($key in $base.Keys) {
        if (!$catalogs[$locale].Contains($key)) { continue }
        $value = ConvertTo-Json -InputObject ([string]$catalogs[$locale][$key]) -Compress
        [void]$output.AppendLine("    {`"$locale`", `"$key`", $value},")
    }
}
$parent = Split-Path -Parent $OutputPath
[void][IO.Directory]::CreateDirectory($parent)
[IO.File]::WriteAllText($OutputPath, $output.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
[void][IO.Directory]::CreateDirectory((Split-Path -Parent $KeysPath))
[IO.File]::WriteAllText($KeysPath, $keys.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Imported $($catalogs.Count) Apple catalogs into $OutputPath"
