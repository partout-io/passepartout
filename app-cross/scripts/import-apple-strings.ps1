[CmdletBinding()]
param(
    [string]$SourceDirectory = "$PSScriptRoot/../../app-apple/Sources/AppStrings/Resources",
    [string]$OutputPath = "$PSScriptRoot/../app/strings/apple_strings.inc"
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function ConvertFrom-AppleEscape([string]$Value) {
    [regex]::Replace($Value, '\\(U[0-9a-fA-F]{4}|u[0-9a-fA-F]{4}|.)', {
        param($Match)
        $escape = $Match.Groups[1].Value
        switch -CaseSensitive ($escape) {
            'n' { "`n" }
            'r' { "`r" }
            't' { "`t" }
            default {
                if ($escape -cmatch '^[Uu][0-9a-fA-F]{4}$') {
                    [string][char][Convert]::ToInt32($escape.Substring(1), 16)
                } elseif ($escape.Length -eq 1 -and $escape -cnotmatch '^[Uu]$') {
                    $escape
                } else {
                    throw "Invalid Apple escape: $escape"
                }
            }
        }
    })
}

function Read-AppleStrings([string]$Path) {
    $text = [IO.File]::ReadAllText($Path)
    $entries = [ordered]@{}
    $position = 0
    $ignored = [regex]'\G(?:\s+|//[^\r\n]*|/\*(?s:.*?)\*/)*'
    $entry = [regex]'\G"((?:\\.|[^"\\])*)"\s*=\s*"((?:\\.|[^"\\])*)"\s*;'
    while ($position -lt $text.Length) {
        $position += $ignored.Match($text, $position).Length
        if ($position -eq $text.Length) { break }
        $match = $entry.Match($text, $position)
        if (!$match.Success) { throw "${Path}: invalid .strings entry at offset $position" }
        $key = ConvertFrom-AppleEscape $match.Groups[1].Value
        if ($entries.Contains($key)) { throw "${Path}: duplicate key $key" }
        $entries[$key] = ConvertFrom-AppleEscape $match.Groups[2].Value
        $position += $match.Length
    }
    return $entries
}

# Emit individual UTF-8 literals to stay below MSVC's string literal size limit.
$catalogs = [ordered]@{}
$base = Read-AppleStrings (Join-Path $SourceDirectory 'en.lproj/Localizable.strings')
foreach ($directory in Get-ChildItem -LiteralPath $SourceDirectory -Directory -Filter '*.lproj' | Sort-Object Name) {
    $locale = $directory.Name.Substring(0, $directory.Name.Length - '.lproj'.Length).Replace('-', '_')
    $entries = Read-AppleStrings (Join-Path $directory.FullName 'Localizable.strings')
    foreach ($key in $base.Keys) {
        if (!$entries.Contains($key) -and !$key.StartsWith('android.')) {
            throw "${locale}: missing key $key"
        }
    }
    foreach ($key in $entries.Keys) {
        if (!$base.Contains($key)) { throw "${locale}: unknown key $key" }
    }
    $catalogs[$locale] = $entries
}
if (!$catalogs.Contains('en')) { throw 'English fallback catalog is required' }
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by scripts/import-apple-strings.ps1. Do not edit.')
foreach ($locale in $catalogs.Keys) {
    foreach ($key in $base.Keys) {
        if (!$catalogs[$locale].Contains($key)) { continue }
        $value = ConvertTo-Json -InputObject ([string]$catalogs[$locale][$key]) -Compress
        [void]$output.AppendLine("    {`"$locale`", `"$key`", $value},")
    }
}
$parent = Split-Path -Parent $OutputPath
[void][IO.Directory]::CreateDirectory($parent)
[IO.File]::WriteAllText($OutputPath, $output.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Imported $($catalogs.Count) Apple catalogs into $OutputPath"
